    function idOf(name) {
        return String(name || '').toLowerCase().replace(/[^a-z0-9]/g, '');
    }

    let factsById;
    function moveFacts() {
        if (factsById) return factsById;
        factsById = new Map(PACKED_FACTS.map(row => {
            const [id, type, category, target, power, priority, flags, preset, intent = '', concept = ''] = row.split('|');
            return [id, { type, category, target, power: Number(power), priority: Number(priority), flags, preset, intent, concept }];
        }));
        return factsById;
    }

    const WARDS = new Set(['auroraveil', 'craftyshield', 'lightscreen', 'luckychant', 'matblock', 'mist', 'quickguard', 'reflect', 'safeguard', 'wideguard']);
    const TRAPS = new Set(['spikes', 'stealthrock', 'stickyweb', 'toxicspikes', 'partiallytrapped', 'trapped', 'leechseed', 'ingrain', 'meanlook', 'block']);

    function readFlags(move) {
        const flags = move.flags || {};
        const flagsByKey = {
            c: flags.contact, s: flags.sound, b: flags.bullet, p: flags.punch,
            l: flags.slicing, h: move.heal || flags.heal, d: move.drain,
            m: move.multihit || move.multiaccuracy, w: move.stallingMove || WARDS.has(move.sideCondition),
            z: move.weather || move.terrain || move.pseudoWeather,
            t: TRAPS.has(move.sideCondition) || TRAPS.has(move.volatileStatus),
            v: move.selfSwitch, n: move.status, q: flags.charge,
            r: move.recoil || move.hasCrashDamage, f: flags.futuremove,
            u: flags.recharge, e: move.selfdestruct, a: flags.powder,
        };
        return Object.keys(flagsByKey).filter(key => flagsByKey[key]).join('');
    }

    function boostMotionKey(boosts = {}) {
        const keys = Object.keys(boosts).filter(stat => boosts[stat] !== 0);
        if (!keys.length) return '';
        if (keys.length === 1) return keys[0];
        if (keys.length > 3) return 'mixed';
        if (keys.includes('spe') && (keys.includes('atk') || keys.includes('spa'))) return 'drive';
        if (keys.every(key => key === 'def' || key === 'spd')) return 'guard';
        if (keys.every(key => key === 'atk' || key === 'spa')) return 'force';
        return 'mixed';
    }

    const SPELL_TRAPS = new Set(['block', 'meanlook', 'spiderweb', 'octolock']);

    function readIntent(move, id) {
        if (move.isMax) return typeof move.isMax === 'string' ? 'form:gmax' : 'form:max';
        if (move.isZ) return 'form:z';
        const field = move.weather || move.terrain || move.pseudoWeather || move.sideCondition;
        if (field && Object.hasOwn(FIELD_MOTION, idOf(field))) return 'field:' + idOf(field);
        if (SPELL_TRAPS.has(id)) return 'trap:' + id;
        if (move.forceSwitch) return 'attack:repel';
        const scripted = Object.hasOwn(SCRIPTED_INTENTS, id) ? SCRIPTED_INTENTS[id] : '';
        if (scripted) return 'script:' + scripted;
        if ((move.category || move.cat) === 'Status') {
            if (move.status && Object.hasOwn(AILMENT_MOTION, move.status) && !move.heal) return 'ailment:' + move.status;
            if (move.volatileStatus && Object.hasOwn(VOLATILE_MOTION, move.volatileStatus)) return 'volatile:' + move.volatileStatus;
            const stat = boostMotionKey(move.boosts || move.self?.boosts);
            if (Object.hasOwn(STAT_MOTION, stat)) {
                const changes = move.boosts || move.self?.boosts;
                return (Object.values(changes).every(amount => amount <= 0) ? 'lower:' : 'raise:') + stat;
            }
            return '';
        }
        if (move.ohko) return 'attack:deliberate';
        if (move.damage !== undefined) return 'attack:fixed';
        if (move.willCrit || move.critRatio > 1) return 'attack:precision';
        return '';
    }

    function metadataFacts(move, facts, id) {
        const isDexRow = Object.hasOwn(move, 'category') && Object.hasOwn(move, 'basePower') && Object.hasOwn(move, 'flags');
        const projected = readFlags(move);
        // UI move rows carry flags, but omit e.g. weather and selfSwitch. Preserve
        // the omitted effects while honoring the row's explicit flag changes.
        const pinned = move.flags ? [...facts.flags].filter(key => !'csbplqfua'.includes(key)) : [...facts.flags];
        const flags = isDexRow ? projected : [...new Set([...pinned, ...projected])].join('');
        return {
            type: move.type || facts.type,
            category: move.category || move.cat || facts.category,
            target: move.target || facts.target,
            power: move.basePower ?? move.pow ?? facts.power,
            priority: move.priority ?? move.pri ?? facts.priority,
            flags,
            preset: facts.preset,
            intent: readIntent(move, id) || (isDexRow ? '' : facts.intent),
            concept: move.realMove ? idOf(move.realMove) : facts.concept,
        };
    }

    // Native move flags take over when no authored visual or legacy technique
    // has a more useful cue. Slicing and contact remain independent properties.
    function mechanicRecipe(flags, family) {
        if (flags.includes('a')) return { path: 'fan', shape: 'dust', impact: 'bind', count: 4 };
        if (flags.includes('s')) return { path: 'pulse', shape: 'note', impact: 'ripple', count: 3 };
        if (flags.includes('l')) return { path: 'arc', shape: 'slash', impact: 'cut' };
        if (family === 'contact' && flags.includes('p')) return { pose: 'snap', shape: 'spark' };
        if (family === 'projectile' && flags.includes('b')) return { path: 'arc', shape: 'orb' };
        if (family === 'status' && flags.includes('n')) return { path: 'drop', impact: 'bind' };
        return {};
    }

    const BROAD_PRESETS = new Set(['', 'ball', 'beam', 'buff', 'debuff', 'tackle', 'punch']);

    function intentRecipe(facts, family) {
        const [intent, detail] = facts.intent.split(':');
        switch (intent) {
        case 'form':
            if (facts.category === 'Status') return {};
            return { ...ELEMENT_MOTION[facts.type], count: detail === 'gmax' ? 7 : detail === 'max' ? 5 : 4 };
        case 'field': return FIELD_MOTION[detail];
        case 'ailment':
            if (facts.flags.includes('a')) return { path: 'fan', shape: 'dust', pose: 'sweep', impact: 'bind', count: 4 };
            if (facts.flags.includes('s')) return { path: 'pulse', shape: 'note', pose: 'still', impact: 'ripple', count: 3 };
            return AILMENT_MOTION[detail];
        case 'volatile': return VOLATILE_MOTION[detail];
        case 'script': return SCRIPTED_MOTION[detail];
        case 'raise': return STAT_MOTION[detail];
        case 'lower': {
            const shift = STAT_MOTION[detail];
            return { ...shift, path: shift.path === 'drop' ? 'ground' : shift.path, impact: 'bind' };
        }
        case 'trap': {
            if (detail === 'octolock') return VOLATILE_MOTION.octolock;
            if (detail === 'spiderweb') return FIELD_MOTION.stickyweb;
            return { path: detail === 'meanlook' ? 'orbit' : 'ground', shape: 'seal', pose: 'still', impact: 'bind', count: 2 };
        }
        case 'attack':
            if (detail === 'repel') return { path: 'fan', shape: 'cone', pose: 'sweep', impact: 'ripple', count: 3 };
            if (!(BROAD_PRESETS.has(facts.preset) && family !== 'contact')) return {};
            if (detail === 'deliberate') return { path: 'direct', shape: 'line', pose: 'focus', impact: 'crack', count: 1 };
            if (detail === 'fixed') return { path: 'pulse', shape: 'ring', pose: 'brace', impact: 'ripple', count: 2 };
            return { path: 'direct', shape: 'shard', pose: 'snap', impact: 'cut', count: 1 };
        default: return {};
        }
    }

    function broadRecipe(id, facts, family) {
        const element = Object.hasOwn(ELEMENT_MOTION, facts.type) ? ELEMENT_MOTION[facts.type] : null;
        if (family === 'contact' && facts.preset === 'bite' && element && id.endsWith('fang')) {
            return { path: element.path === 'drop' ? 'arc' : element.path, shape: element.shape, count: 2 };
        }
        if (!BROAD_PRESETS.has(facts.preset)) return {};
        if (family === 'contact' && facts.flags.includes('c')) {
            if (facts.flags.includes('p') && element && facts.type !== 'Normal') {
                return { path: element.path === 'drop' ? 'arc' : element.path, shape: element.shape, pose: 'snap', count: 2 };
            }
            const technique = CONTACT_TECHNIQUES.find(([pattern]) => pattern.test(id))?.[1];
            if (technique) return technique;
            return element && facts.type !== 'Normal' ? { shape: element.shape, count: Math.min(3, element.count) } : {};
        }
        if (family === 'beam' && element) return { ...element, path: element.path === 'drop' ? 'direct' : element.path, count: Math.min(3, element.count) };
        if (family === 'projectile' || family === 'wave') return element || {};
        return {};
    }

    function getFamily(facts, target) {
        const { category, flags, preset } = facts;
        if (flags.includes('v') || preset === 'pivot' || preset === 'swap_arc') return 'pivot';
        if (flags.includes('z') || preset === 'trick_room') return 'field';
        if (flags.includes('w') || preset === 'shield' || preset === 'sub_doll') return 'ward';
        if (flags.includes('t') || target === 'foe-side' || preset.startsWith('hazard_') || facts.intent.startsWith('trap:')) return 'trap';
        if (flags.includes('d') || preset === 'drain') return 'drain';
        if (category === 'Status') {
            if (flags.includes('h') || preset.startsWith('heal')) return 'heal';
            return target === 'self' || target === 'ally' || target === 'ally-side' ? 'stance' : 'status';
        }
        if (flags.includes('s') || preset === 'pulse' || preset === 'psychic_wave') return 'wave';
        if (flags.includes('e') || ['quake', 'stone_erupt', 'explosion'].includes(preset)) return 'field';
        if (flags.includes('c')) return 'contact';
        if (flags.includes('b') && BROAD_PRESETS.has(preset)) return 'projectile';
        if (['beam', 'bolt', 'flame', 'solar_beam'].includes(preset)) return 'beam';
        if (['wave', 'blizzard', 'vortex'].includes(preset)) return 'wave';
        return !flags.includes('b') && (target === 'spread' || target === 'all') ? 'wave' : 'projectile';
    }

    function generatedPace(facts, base) {
        const [windup, travel, impact, settle] = base.slice(6);
        if (facts.intent.startsWith('form:')) return [windup + 48, travel + 45, impact + 55, settle + 32];
        if (facts.priority > 0 && facts.category !== 'Status') return [30, Math.max(45, travel - 36), impact, Math.max(80, settle - 20)];
        if (facts.flags.includes('q') || facts.flags.includes('u')) return [windup + 65, travel + 28, impact + 42, settle + 30];
        if (facts.power >= 110 || facts.flags.includes('r')) return [windup + 42, travel + 24, impact + 34, settle + 26];
        if (facts.power > 0 && facts.power <= 45) return [Math.max(30, windup - 20), Math.max(48, travel - 24), impact, Math.max(85, settle - 18)];
        return [windup, travel, impact, settle];
    }

    const UNKNOWN_FACTS = { type: 'Normal', category: 'Special', target: 'normal', power: 0, priority: 0, flags: '', preset: '', intent: '', concept: '' };
    const CANONICAL_PROFILES = new Map();

    function makeProfile(id, facts, source) {
        const authored = Object.hasOwn(AUTHORED, id) ? AUTHORED[id] : null;
        const flags = facts.flags;
        const target = flags.includes('z') ? 'field' : Object.hasOwn(TARGETS, facts.target) ? TARGETS[facts.target] : 'target';
        const hiddenPower = id === 'hiddenpower' || facts.concept === 'hiddenpower';
        const family = authored?.family || (hiddenPower ? 'projectile' : getFamily(facts, target));
        const base = FAMILIES[family];
        const original = BROAD_PRESETS.has(facts.preset) ? null : LEGACY_RECIPES[facts.preset];
        const technique = {
            ...mechanicRecipe(flags, family), ...original, ...broadRecipe(id, facts, family),
            ...intentRecipe(facts, family), ...authored,
        };
        // Hidden Power's typed entries are variants of one attack. Keep its
        // signature shell consistent and teach the type with palette and UI.
        if (hiddenPower) Object.assign(technique, { path: 'spiral', shape: 'orb', pose: 'focus', impact: 'ripple', count: 1 });
        const [windup, travel, impact, settle] = technique.timing || generatedPace(facts, base);
        const count = technique.count || (flags.includes('m') ? 3 : ['spread', 'all', 'field'].includes(target) ? 3 : 1);
        let path = technique.path || base[0];
        let pose = technique.pose || base[2];
        if (!authored && family === 'contact' && original?.path === 'drop') path = 'direct';
        if (!authored && family === 'contact' && facts.priority > 0) pose = 'snap';
        return Object.freeze({
            id, family, target, path, shape: technique.shape || base[1], pose,
            impact: technique.impact || base[3],
            sound: technique.sound || base[4], aftermath: technique.aftermath || base[5],
            timing: Object.freeze({ windup, travel, impact, settle }),
            color: Object.freeze([...(technique.color || (Object.hasOwn(TYPES, facts.type) ? TYPES[facts.type] : TYPES.Normal))]),
            count, contact: flags.includes('c'),
            authored: source === 'authored', source,
            category: facts.category, type: facts.type,
            behavior: Object.freeze({
                multihit: flags.includes('m'), charge: flags.includes('q'),
                recharge: flags.includes('u'), delayed: flags.includes('f'),
                recoil: flags.includes('r'), pivot: flags.includes('v'),
            }),
        });
    }

    function get(moveNameOrId, moveMetadata) {
        const id = idOf(moveNameOrId);
        const facts = moveFacts().get(id);
        const source = !facts ? 'fallback' : Object.hasOwn(AUTHORED, id) ? 'authored' : 'generated';
        if (moveMetadata) return makeProfile(id, metadataFacts(moveMetadata, facts || UNKNOWN_FACTS, id), source);
        if (!facts) return makeProfile(id, UNKNOWN_FACTS, source);
        if (!CANONICAL_PROFILES.has(id)) CANONICAL_PROFILES.set(id, makeProfile(id, facts, source));
        return CANONICAL_PROFILES.get(id);
    }

    const registry = Object.freeze({
        get,
        ids: () => [...moveFacts().keys()],
        authoredIds: () => Object.keys(AUTHORED),
    });
    if (typeof module !== 'undefined' && module.exports) {
        module.exports = { ...registry, readFlags, readIntent };
    } else {
        window.BattleMoveProfiles = registry;
    }
