import { build } from 'esbuild';
import { readFile } from 'node:fs/promises';
import { brotliCompressSync, gzipSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { ENGINE_VERSION } from './competitive/arena-simulation.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const lock = JSON.parse(await readFile(new URL('../package-lock.json', import.meta.url), 'utf8'));
if (lock.packages['node_modules/@pkmn/sim'].version !== ENGINE_VERSION) {
  throw new Error('Update the pinned simulator version and rerun the battle parity tests.');
}
const result = await build({
  absWorkingDir: root,
  entryPoints: {
    'showdown-worker': 'scripts/competitive/showdown-worker.mjs',
    'classic-simulation': 'scripts/competitive/classic-simulation.mjs',
  },
  outdir: 'competitive',
  bundle: true,
  minify: true,
  // Showdown's serializer writes constructor names into Side, Pokémon and other state references.
  keepNames: true,
  splitting: true,
  chunkNames: 'showdown-engine',
  platform: 'browser',
  format: 'esm',
  target: 'es2022',
  legalComments: 'eof',
  metafile: true,
  banner: { js: '/* Generated by npm run build:competitive. Third-party licenses: THIRD_PARTY_NOTICES.txt */' },
});
const kib = n => `${Math.round(n / 1024)} KiB`;
for (const asset of Object.keys(result.metafile.outputs)) {
  const bytes = await readFile(new URL(`../${asset}`, import.meta.url));
  console.log(`${asset} ${kib(bytes.length)} raw, ${kib(gzipSync(bytes).length)} gzip, ${kib(brotliCompressSync(bytes).length)} Brotli`);
}
