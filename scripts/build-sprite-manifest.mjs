#!/usr/bin/env node
// Build a manifest of locally available Pokemon sprites and inject it into battle.html.
// Read by getSprite() at runtime: if a slug is in the manifest, serve from local; else go to Showdown.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');
const SPRITES = path.join(ROOT, 'sprites');
const BATTLE_HTML = path.join(ROOT, 'battle.html');

const DIRS = ['gen5ani', 'gen5ani-shiny', 'gen5ani-back', 'gen5ani-back-shiny'];

function listSlugs(dir) {
  const p = path.join(SPRITES, dir);
  if (!fs.existsSync(p)) return [];
  return fs.readdirSync(p)
    .filter((f) => f.endsWith('.gif'))
    .map((f) => f.slice(0, -4))
    .sort();
}

const manifest = {};
for (const d of DIRS) {
  manifest[d] = listSlugs(d);
}

// JSON manifest (also written for tooling / external consumers).
const manifestPath = path.join(SPRITES, 'manifest.json');
fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2));

// Build inline JS block. Each set is `new Set([...])` with the slugs as string literals.
function inlineSet(arr) {
  return arr.map((s) => `"${s}"`).join(',');
}
const inlineJs = `// AUTOGENERATED by scripts/build-sprite-manifest.mjs — do not edit by hand.
        const LOCAL_SPRITE_MANIFEST = {
            'gen5ani': new Set([${inlineSet(manifest['gen5ani'])}]),
            'gen5ani-shiny': new Set([${inlineSet(manifest['gen5ani-shiny'])}]),
            'gen5ani-back': new Set([${inlineSet(manifest['gen5ani-back'])}]),
            'gen5ani-back-shiny': new Set([${inlineSet(manifest['gen5ani-back-shiny'])}]),
        };`;

const html = fs.readFileSync(BATTLE_HTML, 'utf8');
const START = '// LOCAL_SPRITE_MANIFEST_START';
const END = '// LOCAL_SPRITE_MANIFEST_END';
const startIdx = html.indexOf(START);
const endIdx = html.indexOf(END);

if (startIdx === -1 || endIdx === -1) {
  console.error('[manifest] markers not found in battle.html — add them before running.');
  process.exit(1);
}

const before = html.slice(0, startIdx + START.length);
const after = html.slice(endIdx);
const updated = `${before}\n        ${inlineJs}\n        ${after}`;
fs.writeFileSync(BATTLE_HTML, updated);

const totals = DIRS.map((d) => `${d}=${manifest[d].length}`).join(' ');
console.log(`[manifest] wrote ${manifestPath}`);
console.log(`[manifest] patched ${BATTLE_HTML}: ${totals}`);
