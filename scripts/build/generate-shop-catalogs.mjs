#!/usr/bin/env node
// Build-time generator: docs/story-design/story-shops.csv → data/story/shops.json.
// Run after editing the CSV: `node scripts/build/generate-shop-catalogs.mjs`.
//
// Output is the single source of truth for POKEMART_ITEMS / DEPT_ITEMS /
// STONE_SHOP_ITEMS that battle.html loads at boot. The CSV is the editing
// surface (sortable, diffable); the JSON is the runtime artifact.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(__dirname, '..', '..');
const CSV  = path.join(REPO, 'docs', 'story-design', 'story-shops.csv');
const OUT  = path.join(REPO, 'data', 'story', 'shops.json');

// Map from `id` (CSV column) to `ballKey` (battle.html ball convention).
// Add new balls here when introducing them.
const BALL_KEY_BY_ID = {
  pokeBall:   'poke',
  greatBall:  'great',
  ultraBall:  'ultra',
  masterBall: 'master',
  safariBall: 'safari',
};

function parseCsv(text) {
  // Minimal CSV parser: comma-separated, supports double-quoted fields with
  // embedded commas. No escape sequences inside quotes (CSV uses "" for ").
  const rows = [];
  let row = [], field = '', inQuote = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQuote) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; }
        else inQuote = false;
      } else {
        field += c;
      }
    } else {
      if (c === '"') inQuote = true;
      else if (c === ',') { row.push(field); field = ''; }
      else if (c === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
      else if (c === '\r') { /* skip */ }
      else field += c;
    }
  }
  if (field.length || row.length) { row.push(field); rows.push(row); }
  // Drop trailing empty rows
  return rows.filter(r => r.some(cell => cell.length));
}

function rowToItem(row, header) {
  const obj = Object.fromEntries(header.map((h, i) => [h, row[i] ?? '']));
  // Build with key order matching the original inline literals (id, name, price,
  // [kind/effect block], desc). Object key order is functionally irrelevant in
  // JS but matters for clean diffs against the original source.
  const item = { id: obj.id, name: obj.name, price: Number(obj.price) };
  const koe = obj.kindOrEffect;
  if (koe === 'ball') {
    item.kind = 'ball';
    const bk = BALL_KEY_BY_ID[obj.id];
    if (!bk) throw new Error(`No ballKey mapping for id "${obj.id}"; add to BALL_KEY_BY_ID`);
    item.ballKey = bk;
  } else if (koe === 'stone') {
    item.kind = 'stone';
    item.stone = obj.name;
  } else if (koe === 'tradeItem') {
    item.kind = 'tradeItem';
    item.tradeItem = obj.name;
  } else {
    item.effect = koe;
  }
  item.desc = obj.desc;
  // battleBag: false on ball rows (matches inline). Otherwise omit when "yes".
  if (obj.battleBag === 'no') item.battleBag = false;
  return item;
}

function main() {
  const text = fs.readFileSync(CSV, 'utf8');
  const rows = parseCsv(text);
  const header = rows.shift();
  const expected = ['shop','id','name','price','kindOrEffect','battleBag','desc'];
  if (header.join(',') !== expected.join(',')) {
    throw new Error(`Unexpected CSV header. Got: ${header.join(',')}\nWant: ${expected.join(',')}`);
  }
  const byShop = { pokemart: [], dept: [], stone: [] };
  for (const r of rows) {
    const shop = r[0];
    if (!byShop[shop]) throw new Error(`Unknown shop column value "${shop}" (allowed: ${Object.keys(byShop).join(', ')})`);
    byShop[shop].push(rowToItem(r, header));
  }
  const out = {
    _comment: 'Generated by scripts/build/generate-shop-catalogs.mjs from docs/story-design/story-shops.csv. DO NOT edit by hand — edit the CSV and re-run.',
    pokemart: byShop.pokemart,
    dept:     byShop.dept,
    stone:    byShop.stone,
  };
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, JSON.stringify(out, null, 2) + '\n');
  console.log(`[generate-shop-catalogs] wrote ${path.relative(REPO, OUT)}`);
  console.log(`  pokemart: ${byShop.pokemart.length} items`);
  console.log(`  dept:     ${byShop.dept.length} items`);
  console.log(`  stone:    ${byShop.stone.length} items`);
}

main();
